"""Generate src/avogadro_mitsuba/elements.py from Avogadro's elementdata.h.

Usage: python scripts/gen_elements.py path/to/avogadrolibs/avogadro/core/elementdata.h
"""

import re
import sys
from pathlib import Path

DEFAULT_HEADER = Path.home() / "Devel/openchemistry/avogadrolibs/avogadro/core/elementdata.h"
OUTPUT = Path(__file__).resolve().parent.parent / "src/avogadro_mitsuba/elements.py"


def _block(text, name):
    """Return the body of `name[...] = { ... };`, comments stripped."""
    match = re.search(name + r"\[[^=]*=\s*\{(.*?)\n\};", text, re.S)
    if not match:
        raise SystemExit(f"{name} not found in header")
    return re.sub(r"//[^\n]*", "", match.group(1))


def main():
    header = Path(sys.argv[1]) if len(sys.argv) > 1 else DEFAULT_HEADER
    text = header.read_text()

    vdw = [float(x) for x in re.findall(r"[-+]?\d*\.?\d+(?:[eE][-+]?\d+)?",
                                        _block(text, "element_VDW"))]
    colors = [tuple(int(v) for v in m)
              for m in re.findall(r"\{\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\}",
                                  _block(text, "element_color"))]
    symbols = re.findall(r'"(\w+)"', _block(text, "element_symbols"))
    count = len(symbols)
    if len(vdw) != count or len(colors) != count:
        raise SystemExit(f"table sizes differ: {count} {len(vdw)} {len(colors)}")

    out = ['"""Element data generated by scripts/gen_elements.py from',
           'avogadrolibs/avogadro/core/elementdata.h. Do not edit by hand."""', "",
           "# Van der Waals radii in angstrom, indexed by atomic number (0 = dummy)",
           "ELEMENT_VDW = ("]
    out += [f"    {v!r}," for v in vdw]
    out += [")", "", "# sRGB colors (0-255), indexed by atomic number", "ELEMENT_COLOR = ("]
    out += [f"    {c!r}," for c in colors]
    out += [")", ""]
    OUTPUT.write_text("\n".join(out))
    print(f"wrote {OUTPUT} ({count} elements)")


if __name__ == "__main__":
    main()
